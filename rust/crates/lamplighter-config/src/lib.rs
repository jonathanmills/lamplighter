//! Lamplighter's configuration parser, in Rust (stage 1 of
//! doc/RUST-PLAN.md): Robinhood's configuration syntax, with the C
//! parser's syntax trees, line numbers and error messages.
//!
//! It is a translation, not a reinterpretation:
//! - the scanner emulates flex's rule selection on the rules of
//!   conf_lex.l, in their order ([`lexer`]);
//! - the parser runs Bison's algorithm on Bison's own tables for
//!   conf_yacc.y ([`tables`], generated by rust/tools/gen_parser_tables.py),
//!   with that grammar's semantic actions ([`parser`]);
//! - names and values are bytes, cut where the C code cuts them.
//!
//! The side-by-side tests (rust/difftest, stage1.toml and the fuzzer)
//! compare it with the C parser on every test configuration and on
//! randomly mutated ones.

