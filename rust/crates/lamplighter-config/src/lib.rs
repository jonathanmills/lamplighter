pub use tree::{c_print, dump, BoolExpr, Item, Op, SetExpr};

/// Why a configuration could not be parsed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ParseError {
    /// The message the C parser gives (rh_config_GetErrorMsg), as bytes.
    Syntax(Vec<u8>),
    /// A fatal scanner error: the C program prints this and exits with 2.
    Fatal(String),
}

/// The result of parsing a file: the tree or the error, and the warnings
/// the C parser prints on stderr while parsing (undefined variables).
pub struct Parsed {
    pub result: Result<Vec<Item>, ParseError>,
    pub warnings: Vec<Vec<u8>>,
}

/// Parse a configuration file, as `rh_config_ParseFile` does.
pub fn parse_file(path: &[u8]) -> Parsed {
    use std::os::unix::ffi::OsStrExt;
    if path.is_empty() {
        return Parsed { result: Err(ParseError::Syntax(b"Invalid arguments".to_vec())), warnings: Vec::new() };
    }
    let p = std::path::Path::new(std::ffi::OsStr::from_bytes(path));
    let data = match std::fs::File::open(p) {
        Err(e) => {
            let msg = lexer_strerror(e.raw_os_error().unwrap_or(0));
            return Parsed { result: Err(ParseError::Syntax(msg)), warnings: Vec::new() };
        }
        Ok(mut f) => {
            use std::io::Read;
            let mut data = Vec::new();
            if f.read_to_end(&mut data).is_err() {
                return Parsed {
                    result: Err(ParseError::Fatal("input in flex scanner failed".into())),
                    warnings: Vec::new(),
                };
            }
            data
        }
    };
    parse_bytes(path, data)
}

/// Parse configuration text as if it came from the file `path` (used for
/// error messages and relative `%include` paths).
pub fn parse_bytes(path: &[u8], data: Vec<u8>) -> Parsed {
    let mut lx = lexer::Lexer::new(path, data);
    let outcome = parser::parse(&mut lx);
    let result = match outcome {
        parser::Outcome::Tree(items) => Ok(items),
        parser::Outcome::Error(msg) => Err(ParseError::Syntax(msg)),
        parser::Outcome::Fatal(f) => Err(ParseError::Fatal(f.0)),
    };
    Parsed { result, warnings: lx.warnings }
}

fn lexer_strerror(errno: i32) -> Vec<u8> {
    // SAFETY: strerror returns a pointer to a static or thread-local string.
    let p = unsafe { libc::strerror(errno) };
    if p.is_null() {
        return format!("Unknown error {errno}").into_bytes();
    }
    unsafe { std::ffi::CStr::from_ptr(p) }.to_bytes().to_vec()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn parse(s: &str) -> Result<Vec<Item>, ParseError> {
        parse_bytes(b"test.conf", s.as_bytes().to_vec()).result
    }

    #[test]
    fn blocks_affects_and_lines() {
        let t = parse("General {\n  fs_path = /data;\n  x = 'a b' (1, \"2\");\n}\n").unwrap();
        assert_eq!(t.len(), 1);
        let Item::Block { name, content, line, .. } = &t[0] else { panic!() };
        assert_eq!((name.as_slice(), *line), (b"General".as_slice(), 4));
        assert!(matches!(&content[0], Item::Affect { value, line: 2, .. } if value == b"/data"));
        assert!(matches!(&content[1], Item::Affect { args: Some(a), .. } if a == &[b"1".to_vec(), b"2".to_vec()]));
    }

    #[test]
    fn and_or_group_to_the_right() {
        // no precedence in conf_yacc.y: Bison shifts, so a and b or c = a and (b or c)
        let t = parse("FileClass x {\n definition { a == 1 and b == 2 or c == 3 }\n}\n").unwrap();
        let Item::Block { content, .. } = &t[0] else { panic!() };
        let Item::Block { content: def, .. } = &content[0] else { panic!() };
        assert!(matches!(&def[0], Item::BoolExpr { expr: BoolExpr::And(_, b), .. } if matches!(**b, BoolExpr::Or(..))));
    }

    #[test]
    fn keywords_are_case_insensitive() {
        let t = parse("B {\n c { NOT a == 1 }\n}\n").unwrap();
        let Item::Block { content, .. } = &t[0] else { panic!() };
        let Item::Block { content: c, .. } = &content[0] else { panic!() };
        assert!(matches!(&c[0], Item::BoolExpr { expr: BoolExpr::Not(_), .. }));
    }

    #[test]
    fn errors_read_like_the_c_parser() {
        let e = parse("General {\n x = (1;\n}\n").unwrap_err();
        assert_eq!(e, ParseError::Syntax(b"syntax error, unexpected BEGIN_PARENTHESIS, expecting IDENTIFIER or NON_IDENTIFIER_VALUE or ENV_VAR at '(' line 2 in 'test.conf'".to_vec()));
    }

    #[test]
    fn comment_without_final_newline_is_an_error() {
        // `#.*$` needs the newline: at end of file the comment does not match
        assert!(parse("General { x = 1; }\n# last line").is_err());
        assert!(parse("General { x = 1; }\n# last line\n").is_ok());
    }
}
