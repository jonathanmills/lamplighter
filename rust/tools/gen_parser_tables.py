"""Copy Bison's parse tables for the configuration grammar into Rust.

The Rust configuration parser (crates/lamplighter-config) runs the same
LALR(1) algorithm as Bison's C skeleton, on the same tables, so its trees,
line numbers and error messages match the C parser's by construction.
This reads the conf_yacc.c that Bison generates from
src/cfg_parsing/conf_yacc.y in a C build, and writes src/tables.rs.

Bison's licence allows its parser tables to be used under any licence.

Usage: gen_parser_tables.py CONF_YACC_C OUT_RS        (write)
       gen_parser_tables.py --check CONF_YACC_C OUT_RS (fail if out of date)
"""

import re
import sys

ARRAYS = ["yytranslate", "yypact", "yydefact", "yypgoto", "yydefgoto",
          "yytable", "yycheck", "yyr1", "yyr2"]
DEFINES = ["YYFINAL", "YYLAST", "YYNTOKENS", "YYNNTS", "YYNRULES", "YYNSTATES",
           "YYMAXUTOK", "YYPACT_NINF", "YYTABLE_NINF", "YYUNDEFTOK",
           "YYINITDEPTH", "YYMAXDEPTH", "YYTERROR"]


def extract(c: str) -> str:
    out = ["// Generated by rust/tools/gen_parser_tables.py from Bison's output for",
           "// src/cfg_parsing/conf_yacc.y. Do not edit: regenerate it.",
           "// Bison's licence allows these tables to be used under any licence.",
           "#![allow(dead_code)]", ""]
    m = re.search(r"/\* A Bison parser, made by GNU Bison ([0-9]+(?:\.[0-9]+)*)", c)
    out.append(f"/// The Bison version that generated these tables.")
    out.append(f'pub const BISON_VERSION: &str = "{m.group(1) if m else "unknown"}";')
    for d in DEFINES:
        m = re.search(rf"#\s*define {d}\s+\(?(-?\d+)\)?", c)
        if not m:
            raise SystemExit(f"{d} not found")
        out.append(f"pub const {d}: i32 = {m.group(1)};")
    for name in ARRAYS:
        m = re.search(rf"static const \w+ {name}\[\] =\s*\{{(.*?)\}};", c, re.S)
        if not m:
            raise SystemExit(f"{name} not found")
        values = [int(v) for v in re.findall(r"-?\d+", m.group(1))]
        out.append(f"pub static {name.upper()}: [i32; {len(values)}] = [")
        for i in range(0, len(values), 16):
            out.append("    " + ", ".join(str(v) for v in values[i:i + 16]) + ",")
        out.append("];")
    m = re.search(r"static const char \*const yytname\[\] =\s*\{(.*?)\};", c, re.S)
    names = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))
    out.append(f"pub static YYTNAME: [&str; {len(names)}] = [")
    for n in names:
        out.append(f'    "{n}",')
    out.append("];")
    return "\n".join(out) + "\n"


def main() -> int:
    check = sys.argv[1] == "--check"
    src, dst = sys.argv[2:4] if check else sys.argv[1:3]
    text = extract(open(src).read())
    if check:
        if open(dst).read() != text:
            print(f"{dst} is out of date: regenerate it with {sys.argv[0]}", file=sys.stderr)
            return 1
        print(f"{dst}: up to date")
        return 0
    open(dst, "w").write(text)
    print(f"wrote {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
